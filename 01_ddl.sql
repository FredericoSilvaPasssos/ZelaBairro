-- ---------------------------------------------------------------------
-- Limpeza (permite rodar o script mais de uma vez)
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('T_ZB_LOG_ERRO','T_ZB_INDICADOR_MENSAL','T_ZB_HISTORICO_STATUS',
                                   'T_ZB_APOIO','T_ZB_OCORRENCIA','T_ZB_CIDADAO','T_ZB_CATEGORIA',
                                   'T_ZB_ORGAO','T_ZB_BAIRRO')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
    FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name = 'SEQ_ZB_PROTOCOLO') LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- BAIRRO: região onde o problema acontece
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_BAIRRO (
    id_bairro      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_bairro      VARCHAR2(60)  NOT NULL,
    nm_cidade      VARCHAR2(60)  NOT NULL,
    sg_uf          CHAR(2)       NOT NULL,
    CONSTRAINT pk_zb_bairro PRIMARY KEY (id_bairro),
    CONSTRAINT uk_zb_bairro UNIQUE (nm_bairro, nm_cidade, sg_uf)
);

-- ---------------------------------------------------------------------
-- ORGAO: órgão público responsável pelo atendimento (com prazo/SLA)
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_ORGAO (
    id_orgao           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_orgao           VARCHAR2(80)  NOT NULL,
    ds_email           VARCHAR2(100),
    nr_prazo_dias_sla  NUMBER(3)     DEFAULT 7 NOT NULL,
    CONSTRAINT pk_zb_orgao PRIMARY KEY (id_orgao),
    CONSTRAINT ck_zb_orgao_sla CHECK (nr_prazo_dias_sla > 0)
);

-- ---------------------------------------------------------------------
-- CATEGORIA: tipo do problema; peso entra no cálculo de prioridade
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_CATEGORIA (
    id_categoria   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    cd_categoria   VARCHAR2(30)  NOT NULL,
    nm_categoria   VARCHAR2(60)  NOT NULL,
    nr_peso        NUMBER(1)     NOT NULL,
    id_orgao       NUMBER        NOT NULL,
    CONSTRAINT pk_zb_categoria PRIMARY KEY (id_categoria),
    CONSTRAINT uk_zb_categoria_cd UNIQUE (cd_categoria),
    CONSTRAINT ck_zb_categoria_peso CHECK (nr_peso BETWEEN 1 AND 4),
    CONSTRAINT fk_zb_categoria_orgao FOREIGN KEY (id_orgao) REFERENCES T_ZB_ORGAO (id_orgao)
);

-- ---------------------------------------------------------------------
-- CIDADAO: usuário do aplicativo
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_CIDADAO (
    id_cidadao     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_cidadao     VARCHAR2(100) NOT NULL,
    ds_email       VARCHAR2(100) NOT NULL,
    nr_telefone    VARCHAR2(15),
    dt_cadastro    DATE          DEFAULT SYSDATE NOT NULL,
    id_bairro      NUMBER        NOT NULL,
    CONSTRAINT pk_zb_cidadao PRIMARY KEY (id_cidadao),
    CONSTRAINT uk_zb_cidadao_email UNIQUE (ds_email),
    CONSTRAINT fk_zb_cidadao_bairro FOREIGN KEY (id_bairro) REFERENCES T_ZB_BAIRRO (id_bairro)
);

-- ---------------------------------------------------------------------
-- OCORRENCIA: problema registrado em espaço público (entidade central)
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_OCORRENCIA (
    id_ocorrencia        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    cd_protocolo         VARCHAR2(20)   NOT NULL,
    ds_titulo            VARCHAR2(80)   NOT NULL,
    ds_descricao         VARCHAR2(500)  NOT NULL,
    ds_endereco          VARCHAR2(120)  NOT NULL,
    ds_ponto_referencia  VARCHAR2(120),
    fl_acessibilidade    CHAR(1)        DEFAULT 'N' NOT NULL,
    st_ocorrencia        VARCHAR2(20)   DEFAULT 'REGISTRADA' NOT NULL,
    qt_apoios            NUMBER(6)      DEFAULT 0 NOT NULL,
    nr_pontuacao         NUMBER(3)      DEFAULT 0 NOT NULL,
    ds_prioridade        VARCHAR2(5)    DEFAULT 'BAIXA' NOT NULL,
    dt_abertura          DATE           DEFAULT SYSDATE NOT NULL,
    dt_atualizacao       DATE           DEFAULT SYSDATE NOT NULL,
    dt_resolucao         DATE,
    id_cidadao           NUMBER         NOT NULL,
    id_categoria         NUMBER         NOT NULL,
    id_bairro            NUMBER         NOT NULL,
    CONSTRAINT pk_zb_ocorrencia PRIMARY KEY (id_ocorrencia),
    CONSTRAINT uk_zb_ocorrencia_protocolo UNIQUE (cd_protocolo),
    CONSTRAINT ck_zb_ocorrencia_acess CHECK (fl_acessibilidade IN ('S','N')),
    CONSTRAINT ck_zb_ocorrencia_status CHECK (st_ocorrencia IN ('REGISTRADA','EM_ANALISE','EM_ATENDIMENTO','RESOLVIDA')),
    CONSTRAINT ck_zb_ocorrencia_prior CHECK (ds_prioridade IN ('ALTA','MEDIA','BAIXA')),
    CONSTRAINT ck_zb_ocorrencia_apoios CHECK (qt_apoios >= 0),
    CONSTRAINT fk_zb_ocorrencia_cidadao FOREIGN KEY (id_cidadao) REFERENCES T_ZB_CIDADAO (id_cidadao),
    CONSTRAINT fk_zb_ocorrencia_categoria FOREIGN KEY (id_categoria) REFERENCES T_ZB_CATEGORIA (id_categoria),
    CONSTRAINT fk_zb_ocorrencia_bairro FOREIGN KEY (id_bairro) REFERENCES T_ZB_BAIRRO (id_bairro)
);

CREATE INDEX ix_zb_ocorrencia_status    ON T_ZB_OCORRENCIA (st_ocorrencia);
CREATE INDEX ix_zb_ocorrencia_categoria ON T_ZB_OCORRENCIA (id_categoria);
CREATE INDEX ix_zb_ocorrencia_bairro    ON T_ZB_OCORRENCIA (id_bairro);

-- ---------------------------------------------------------------------
-- APOIO: associativa N:N entre CIDADAO e OCORRENCIA ("também sou afetado")
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_APOIO (
    id_ocorrencia  NUMBER NOT NULL,
    id_cidadao     NUMBER NOT NULL,
    dt_apoio       DATE   DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_zb_apoio PRIMARY KEY (id_ocorrencia, id_cidadao),
    CONSTRAINT fk_zb_apoio_ocorrencia FOREIGN KEY (id_ocorrencia) REFERENCES T_ZB_OCORRENCIA (id_ocorrencia),
    CONSTRAINT fk_zb_apoio_cidadao FOREIGN KEY (id_cidadao) REFERENCES T_ZB_CIDADAO (id_cidadao)
);

-- ---------------------------------------------------------------------
-- HISTORICO_STATUS: linha do tempo do atendimento (preenchida por trigger)
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_HISTORICO_STATUS (
    id_historico   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_ocorrencia  NUMBER        NOT NULL,
    st_anterior    VARCHAR2(20),
    st_novo        VARCHAR2(20)  NOT NULL,
    ds_observacao  VARCHAR2(300),
    dt_alteracao   DATE          DEFAULT SYSDATE NOT NULL,
    nm_usuario_bd  VARCHAR2(60)  DEFAULT USER NOT NULL,
    CONSTRAINT pk_zb_historico PRIMARY KEY (id_historico),
    CONSTRAINT fk_zb_historico_ocorrencia FOREIGN KEY (id_ocorrencia) REFERENCES T_ZB_OCORRENCIA (id_ocorrencia)
);

CREATE INDEX ix_zb_historico_ocorrencia ON T_ZB_HISTORICO_STATUS (id_ocorrencia);

-- ---------------------------------------------------------------------
-- INDICADOR_MENSAL: indicadores consolidados por bairro/categoria/mês
-- (gerados pela procedure PKG_ZELABAIRRO.gerar_indicadores_mensais)
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_INDICADOR_MENSAL (
    id_indicador          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nr_ano_mes            NUMBER(6)   NOT NULL,
    id_bairro             NUMBER      NOT NULL,
    id_categoria          NUMBER      NOT NULL,
    qt_registradas        NUMBER(6)   DEFAULT 0 NOT NULL,
    qt_resolvidas         NUMBER(6)   DEFAULT 0 NOT NULL,
    qt_fora_prazo         NUMBER(6)   DEFAULT 0 NOT NULL,
    qt_apoios             NUMBER(8)   DEFAULT 0 NOT NULL,
    nr_tempo_medio_horas  NUMBER(8,2),
    pc_resolucao          NUMBER(5,2),
    dt_geracao            DATE        DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_zb_indicador PRIMARY KEY (id_indicador),
    CONSTRAINT uk_zb_indicador UNIQUE (nr_ano_mes, id_bairro, id_categoria),
    CONSTRAINT fk_zb_indicador_bairro FOREIGN KEY (id_bairro) REFERENCES T_ZB_BAIRRO (id_bairro),
    CONSTRAINT fk_zb_indicador_categoria FOREIGN KEY (id_categoria) REFERENCES T_ZB_CATEGORIA (id_categoria)
);

-- ---------------------------------------------------------------------
-- LOG_ERRO: auditoria de erros das rotinas PL/SQL
-- ---------------------------------------------------------------------
CREATE TABLE T_ZB_LOG_ERRO (
    id_log         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_rotina      VARCHAR2(60)   NOT NULL,
    cd_erro        NUMBER,
    ds_erro        VARCHAR2(4000),
    dt_erro        DATE           DEFAULT SYSDATE NOT NULL,
    nm_usuario_bd  VARCHAR2(60)   DEFAULT USER NOT NULL,
    CONSTRAINT pk_zb_log_erro PRIMARY KEY (id_log)
);

-- Sequência usada para montar o número de protocolo (ZB-AAMMDD-000001)
CREATE SEQUENCE SEQ_ZB_PROTOCOLO START WITH 1 INCREMENT BY 1 NOCACHE;

-- Comentários (dicionário de dados)
COMMENT ON TABLE  T_ZB_OCORRENCIA IS 'Problemas em espaços públicos registrados pelos cidadãos';
COMMENT ON COLUMN T_ZB_OCORRENCIA.nr_pontuacao IS 'peso da categoria + 3 se afeta acessibilidade + apoios (máx. 10)';
COMMENT ON COLUMN T_ZB_OCORRENCIA.ds_prioridade IS 'ALTA (>=10), MEDIA (>=6) ou BAIXA, calculada por trigger';
COMMENT ON TABLE  T_ZB_APOIO IS 'Cidadãos que confirmam ser afetados pela mesma ocorrência';
COMMENT ON TABLE  T_ZB_HISTORICO_STATUS IS 'Linha do tempo de cada ocorrência, alimentada por trigger';
